// ── Lookups ───────────────────────────────────────────────────────────────────

const COLOR_BY_ID = new Map(COLOR_PRESETS.map((c) => [c.id, c]));
const EFFECT_BY_ID = new Map(EFFECT_PRESETS.map((e) => [e.id, e]));

export function findColorPreset(id: string | null | undefined): ColorPreset | null {
  return id ? COLOR_BY_ID.get(id) ?? null : null;
}

export function findEffectPreset(id: string | null | undefined): EffectPreset | null {
  return id ? EFFECT_BY_ID.get(id) ?? null : null;
}

/**
 * Bounds for the free-form HSL picker.
 *
 * `minLightness` here is only the ABSOLUTE floor of the slider. The real per-hue floor
 * is computed live by `minLightnessForHue()` — luminance weights the channels very
 * unevenly, so saturated blue needs ~76% lightness to be legible while red and green
 * clear the bar far lower, and a single flat floor would either wash out every hue or
 * let blue through illegibly. The picker clamps per-hue as the user drags; the
 * validator then re-checks the exact resulting colour server-side regardless.
 */
export const CUSTOM_COLOR_BOUNDS = {
  minLightness: 40,
  maxLightness: 92,
  minSaturation: 25,
  maxSaturation: 100,
} as const;

