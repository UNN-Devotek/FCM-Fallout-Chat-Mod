/**
 * The cosmetics catalog — colours and effects, with their tier gates.
 *
 * This module is the SINGLE SOURCE OF TRUTH. It is served over
 * GET /api/cosmetics/catalog and consumed by the web Profile panel, the Discord
 * `/cosmetics` autocomplete, and the validator — nothing re-declares the list.
 *
 * Every colour here is machine-verified by cosmeticsCatalog.test.ts against two gates:
 *   - contrast: worst-case WCAG ratio >= MIN_CONTRAST across every surface a name
 *     renders on (see utils/colorContrast.ts)
 *   - reserved: far enough from every role / theme / channel colour that it cannot be
 *     used to impersonate staff or imitate system chrome (see reservedColors.ts)
 * A bad preset therefore fails CI rather than shipping and being discovered in chat.
 *
 * The palette was generated by farthest-point selection over HSL space subject to both
 * gates, so the colours are maximally distinguishable from each other in the picker
 * rather than hand-picked and accidentally similar.
 */
import { SupporterTier } from '../../utils/supporterTier';

export interface ColorPreset {
  id: string;
  label: string;
  hex: string;
  /** Minimum tier required. 'none' = available to everyone. */
  tier: SupporterTier;
}

export interface EffectPreset {
  id: string;
  label: string;
  tier: SupporterTier;
  /** Short user-facing explanation, reused verbatim by the web UI and Discord. */
  description: string;
  /**
   * Whether the effect renders in the in-game HUD.
   *
   * ALWAYS false for effects, and this is permanent, not a TODO. Scaleform crashes
   * the game outright on any `.filters` assignment (FCMChatWidget.hx crash rule #1,
   * "violations crashed the game in production") and `StyleSheet` is banned too, so
   * glow, gradient and animation cannot exist in-game at any point in the future.
   * Solid colours and text prefixes are the entire in-game surface.
   *
   * Surfaced through the API so the UI can label effects honestly rather than selling
   * someone a cosmetic that silently does nothing where they play.
   */
  inGameSupported: false;
  /** True when the effect animates — drives the reduced-motion / opt-out collapse. */
  animated: boolean;
}

